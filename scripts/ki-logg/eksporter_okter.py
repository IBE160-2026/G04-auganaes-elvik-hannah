#!/usr/bin/env python3
"""Eksporter Claude Code-økter for dette repoet til lesbare Markdown-filer i docs/ki-logg/okter/.

Claude Code lagrer hver økt som en JSONL-transkripsjon under ~/.claude/projects/<prosjekt>/.
Skriptet henter ut det mennesket skrev (prompts, svar på spørsmål fra KI, avviste
verktøykall og avbrytelser) og kobler økta til commits som ble gjort i samme tidsrom.
KI-ens egne svar tas ikke med; sammendrag per økt står i docs/ki-logg/README.md.

Bruk:
    python3 scripts/ki-logg/eksporter_okter.py           # eksporter alle økter for repoet
    python3 scripts/ki-logg/eksporter_okter.py --hook    # kalles av Stop-hooken (leser JSON fra stdin)
"""
import argparse
import json
import re
import subprocess
import sys
from datetime import datetime, timedelta
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
UT_MAPPE = REPO / "docs" / "ki-logg" / "okter"

STOY_PREFIKS = (
    "<local-command-stdout>",
    "<local-command-stderr>",
    "<local-command-caveat>",
    "Caveat: The messages below were generated by the user while running local commands",
    "<task-notification>",  # varsel om at en bakgrunnsjobb er ferdig, ikke skrevet av brukeren
    "<bash-stdout>",
    "<bash-stderr>",
)
INNEBYGDE_KOMMANDOER = {"/clear", "/compact", "/exit", "/model", "/config", "/status", "/cost", "/resume", "/login", "/logout", "/fast"}
AVSLATT_MARKOR = "The user doesn't want to proceed with this tool use"
AVBRUTT_MARKOR = "[Request interrupted by user"


def sensurer(tekst):
    """Fjern personlige stier, e-postadresser og ting som ligner API-nøkler."""
    tekst = re.sub(r"/Users/[^/\s]+", "~", tekst)
    tekst = re.sub(r"C:\\\\Users\\\\[^\\\s]+", "~", tekst)
    tekst = re.sub(r"[\w.+-]+@[\w-]+\.[\w.-]+", "[e-post fjernet]", tekst)
    tekst = re.sub(r"\b(sk-[A-Za-z0-9_-]{16,}|AIza[0-9A-Za-z_-]{20,}|eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9._-]+)", "[nøkkel fjernet]", tekst)
    return tekst


def tekst_fra_innhold(innhold):
    if isinstance(innhold, str):
        return innhold
    deler = []
    for blokk in innhold or []:
        if blokk.get("type") == "text":
            deler.append(blokk.get("text", ""))
        elif blokk.get("type") == "image":
            deler.append("_[bilde vedlagt]_")
    return "\n".join(deler)


def rens_prompt(tekst):
    """Returner prompten slik brukeren skrev den, eller None hvis det er systemstøy."""
    tekst = re.sub(r"<system-reminder>.*?</system-reminder>", "", tekst, flags=re.S).strip()
    if not tekst or tekst.startswith(STOY_PREFIKS):
        return None
    kommando = re.search(r"<command-name>(.*?)</command-name>", tekst, flags=re.S)
    if kommando:
        navn = kommando.group(1).strip()
        if navn in INNEBYGDE_KOMMANDOER:
            return None
        args = re.search(r"<command-args>(.*?)</command-args>", tekst, flags=re.S)
        args = args.group(1).strip() if args else ""
        return f"`{navn}`" + (f" {args}" if args else "")
    skall = re.match(r"<bash-input>(.*?)</bash-input>", tekst, flags=re.S)
    if skall:
        return f"`! {skall.group(1).strip()}`"
    if tekst.startswith(AVBRUTT_MARKOR):
        return "_(brukeren avbrøt KI-en)_"
    return tekst


def tolk_okt(sti):
    hendelser = []  # (tidspunkt, type, tekst)
    verktoy_navn = {}
    for linje in sti.open(encoding="utf-8"):
        try:
            d = json.loads(linje)
        except json.JSONDecodeError:
            continue
        if d.get("isSidechain") or d.get("isMeta"):
            continue
        melding = d.get("message") or {}
        innhold = melding.get("content")
        if d.get("type") == "assistant" and isinstance(innhold, list):
            for blokk in innhold:
                if blokk.get("type") == "tool_use":
                    verktoy_navn[blokk.get("id")] = blokk.get("name")
            continue
        if d.get("type") != "user" or "timestamp" not in d:
            continue
        tid = datetime.fromisoformat(d["timestamp"].replace("Z", "+00:00")).astimezone()
        if isinstance(innhold, list) and any(b.get("type") == "tool_result" for b in innhold):
            for blokk in innhold:
                if blokk.get("type") != "tool_result":
                    continue
                resultat = tekst_fra_innhold(blokk.get("content"))
                navn = verktoy_navn.get(blokk.get("tool_use_id"))
                if navn == "AskUserQuestion":
                    if AVSLATT_MARKOR in resultat:
                        resultat = "_(valgte ingen av alternativene, svarte med egne ord i neste prompt)_"
                    resultat = re.sub(r"^(User has answered your questions|Your questions have been answered|The user answered):\s*", "", resultat.strip())
                    resultat = re.sub(r"\s*(You can now continue with (the user's|these) answers in mind|Read the answers carefully\b.*)\.?$", "", resultat)
                    hendelser.append((tid, "svar", resultat.strip()))
                elif AVSLATT_MARKOR in resultat:
                    grunn = resultat.split("the user said:", 1)
                    grunn = grunn[1].strip() if len(grunn) > 1 else ""
                    hendelser.append((tid, "avslag", f"Avviste `{navn}`" + (f": {grunn}" if grunn else "")))
            continue
        prompt = rens_prompt(tekst_fra_innhold(innhold))
        if prompt:
            hendelser.append((tid, "prompt", prompt))
    return hendelser


def aktive_perioder(tider, pause=timedelta(hours=2)):
    """Del økta i perioder med aktivitet; en økt kan gjenopptas flere dager senere."""
    perioder = [[tider[0], tider[0]]]
    for tid in tider[1:]:
        if tid - perioder[-1][1] > pause:
            perioder.append([tid, tid])
        else:
            perioder[-1][1] = tid
    return perioder


def commits_i_okta(tider):
    commits = {}
    for start, slutt in aktive_perioder(tider):
        resultat = subprocess.run(
            ["git", "-C", str(REPO), "log", "--all", "--date=format-local:%Y-%m-%d %H:%M",
             f"--since={start.isoformat()}", f"--until={(slutt + timedelta(minutes=15)).isoformat()}",
             "--format=%h|%ad|%an|%s"],
            capture_output=True, text=True, encoding="utf-8", errors="replace",
        )
        for linje in resultat.stdout.splitlines():
            if linje:
                commits[linje.split("|", 1)[0]] = linje.split("|", 3)
    return sorted(commits.values(), key=lambda c: c[1])


def git_bruker():
    navn = subprocess.run(["git", "-C", str(REPO), "config", "user.name"], capture_output=True, text=True, encoding="utf-8", errors="replace").stdout.strip()
    return navn or "ukjent"


def lag_markdown(sti, hendelser, forfatter):
    start, slutt = hendelser[0][0], hendelser[-1][0]
    antall = sum(1 for h in hendelser if h[1] == "prompt")
    linjer = [
        f"# KI-økt {start:%Y-%m-%d} – {forfatter}",
        "",
        f"- **Økt-ID:** `{sti.stem}`",
        f"- **Tidsrom:** {start:%Y-%m-%d %H:%M} – {slutt:%Y-%m-%d %H:%M}",
        f"- **Verktøy:** Claude Code",
        f"- **Antall prompts:** {antall}",
        "",
        "Generert automatisk av `scripts/ki-logg/eksporter_okter.py`. Promptene er gjengitt ordrett;",
        "personlige stier og e-postadresser er fjernet. Sammendrag av økta står i `docs/ki-logg/README.md`.",
        "",
        "## Commits gjort mens økta var aktiv",
        "",
    ]
    commits = commits_i_okta([h[0] for h in hendelser])
    linjer += [f"- `{h}` {dato} ({navn}) {emne}" for h, dato, navn, emne in commits] or ["_Ingen._"]
    linjer += ["", "## Logg", ""]
    etiketter = {"prompt": "Prompt", "svar": "Svar på spørsmål fra KI", "avslag": "Avviste KI-forslag"}
    for nr, (tid, type_, tekst) in enumerate(hendelser, 1):
        linjer.append(f"### {nr}. {etiketter[type_]} · {tid:%Y-%m-%d %H:%M}")
        linjer.append("")
        linjer += ["> " + l if l.strip() else ">" for l in sensurer(tekst).splitlines()]
        linjer.append("")
    return start, "\n".join(linjer)


def eksporter(sti, forfatter):
    hendelser = tolk_okt(sti)
    if not any(h[1] == "prompt" for h in hendelser):
        return None
    start, markdown = lag_markdown(sti, hendelser, forfatter)
    slug = re.sub(r"[^a-z0-9]+", "-", forfatter.lower()).strip("-")
    UT_MAPPE.mkdir(parents=True, exist_ok=True)
    ut = UT_MAPPE / f"{start:%Y-%m-%d}_{slug}_{sti.stem[:8]}.md"
    ut.write_text(markdown + "\n", encoding="utf-8")
    return ut


def prosjektmappe():
    """Claude Code navngir mappa etter repo-stien med alle andre tegn enn bokstaver/tall byttet til '-'."""
    projects = Path.home() / ".claude" / "projects"
    navn = re.sub(r"[^A-Za-z0-9]", "-", str(REPO))
    if (projects / navn).is_dir():
        return projects / navn
    # Windows: stasjonsbokstaven kan ha ulik store/små bokstaver
    for mappe in projects.glob("*"):
        if mappe.name.lower() == navn.lower():
            return mappe
    return projects / navn


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--hook", action="store_true", help="les transcript_path fra hook-JSON på stdin")
    args = parser.parse_args()
    forfatter = git_bruker()

    if args.hook:
        try:
            try:
                sys.stdin.reconfigure(encoding="utf-8")
                sti = Path(json.load(sys.stdin)["transcript_path"])
            except (ValueError, KeyError):
                # Mangler hook-data: ta den sist endrede økta
                sti = max(prosjektmappe().glob("*.jsonl"), key=lambda f: f.stat().st_mtime)
            if sti.exists():
                eksporter(sti, forfatter)
        except Exception as feil:  # hooken skal aldri stoppe arbeidet
            print(f"ki-logg: eksport feilet: {feil}", file=sys.stderr)
        return

    mappe = prosjektmappe()
    if not mappe.is_dir():
        sys.exit(f"Fant ingen Claude Code-økter i {mappe}")
    for sti in sorted(mappe.glob("*.jsonl")):
        ut = eksporter(sti, forfatter)
        if ut:
            print(f"Skrev {ut.relative_to(REPO)}")


if __name__ == "__main__":
    main()
